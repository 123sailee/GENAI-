# FUNCTION 1: Display all destinations

def display_places():

    print("\n========== ALL DESTINATIONS ==========")

    for place in places:
        print(
            f"{place['id']}. {place['place']} | "
            f"{place['district']} | {place['category']}"
        )


# FUNCTION 2: Search destination by keyword

def search_place(keyword):

    print(f"\nSearching for: {keyword}")

    found = False

    for place in places:

        if keyword.lower() in place["place"].lower():

            print("\nDestination Found!")
            print("Name:", place["place"])
            print("District:", place["district"])
            print("Category:", place["category"])
            print("Best Season:", place["best_season"])

            found = True

    if not found:
        print("No destination found.")


# FUNCTION 3: Count destinations by category

def count_by_category():

    category_count = {}

    for place in places:

        category = place["category"]

        if category in category_count:
            category_count[category] += 1

        else:
            category_count[category] = 1

    print("\n========== CATEGORY COUNT ==========")

    for category, count in category_count.items():

        print(f"{category}: {count}")


